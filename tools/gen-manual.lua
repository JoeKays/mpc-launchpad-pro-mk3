#!/usr/bin/env lua5.4
-- gen-manual.lua — render docs/MANUAL.md from the controller script itself.
--
-- The manual is GENERATED: the single source of truth is the ACTIONS table (and
-- the palette / mapping tables) inside script/LaunchpadProMK3.lua. Run
-- tools/gen-manual.sh to regenerate; tests/run-tests.sh fails when the committed
-- manual is stale.
--
-- Usage: tools/gen-manual.lua [source.lua] [output.md]

local src = arg[1] or "script/LaunchpadProMK3.lua"
local out = arg[2] or "docs/MANUAL.md"

package.path = "./tests/?.lua;" .. package.path
local mock = require("mock-mpc")
_G.mpc = mock.mpc
_G.dev = mock.dev
_G.LaunchpadProMK3 = mock.dev
dofile(os.getenv("LPP3_LUA") or src)

local L = LaunchpadProMK3
local ACTIONS = L.ACTIONS
assert(type(ACTIONS) == "table", "the script did not expose ACTIONS")
local P = L.PALETTE
assert(type(P) == "table", "the script did not expose PALETTE")

local order = {
	"top", "right", "left", "track",
}
local groups = {
	top = { title = "Top row (CC 90-98)", ccs = { 90, 91, 92, 93, 94, 95, 96, 97, 98 } },
	right = { title = "Right column (scene buttons)", ccs = { 89, 79, 69, 59, 49, 39, 29, 19 } },
	left = { title = "Left column (CC 10-80)", ccs = { 10, 20, 30, 40, 50, 60, 70, 80 } },
	track = { title = "Function buttons (CC 1-8)", ccs = { 1, 2, 3, 4, 5, 6, 7, 8 } },
}

local lines = {}
local function add(s)
	lines[#lines + 1] = s or ""
end

local function colourRow(name, c)
	return string.format("| %s | %d, %d, %d |", name, c[1], c[2], c[3])
end

add("# Launchpad Pro MK3 controller manual")
add()
add("Generated from `script/LaunchpadProMK3.lua` by `tools/gen-manual.sh`.")
add("Do not edit this file: edit the script and regenerate.")
add()
add("## Grid")
add()
add("The 8x8 pads are notes 11-88, bottom-left first. The pad window shows the")
add("MPC clip matrix; the arrows move the window. Row 0 is the top row of pads.")
add()
add("```")
add("  top row:  90 Shift   91 <   92 >   93 Session  94 Note  95 Chord  96 Custom  97 Seq  98 Save")
add("  right:    89 Patterns  79 Steps  69 Pattern settings  59 Velocity")
add("            49 Probability  39 Mutation  29 Micro step  19 Print to clip")
add("  left:     80 Up   70 Down   60 Clear   50 Duplicate   40 Quantize")
add("            30 Fixed length   20 Play   10 Record")
add("  bottom:   1 RecArm  2 Mute  3 Solo  4 Volume  5 Pan  6 Sends  7 Device  8 StopClip")
add("  pads:     notes 11-88 (8x8), bottom-left = note 11")
add("```")
add()
for _, key in ipairs(order) do
	local g = groups[key]
	add("## " .. g.title)
	add()
	add("| CC | Button | Press | Shift + press |")
	add("|----|--------|-------|---------------|")
	for _, cc in ipairs(g.ccs) do
		local a = ACTIONS[cc]
		assert(a, "ACTIONS has no entry for CC " .. cc)
		add(string.format("| %d | %s | %s | %s |", cc, a.label, a.plain, a.shift))
	end
	add()
end
add("## Track row (CC 101-108)")
add()
add("| CC | Press |")
add("|----|-------|")
for i = 0, 7 do
	add(string.format("| %d | select the track in that column (hold a function button to apply it) |", 101 + i))
end
add()
add("## Pages")
add()
add("- **Clip grid** (default): pads launch clips; Shift + pad selects without")
add("  launching; an empty pad stops the track.")
add("- **MPC pads mode** (Note): the bottom-left 4x4 mirrors the MPC pads for drum")
add("  tracks; melodic tracks get 64 pads across the four banks.")
add("- **Volume / pan / sends menus** (function buttons 4/5/6): each track column is")
add("  a fader; press the button again to exit.")
add("- **Q-Link page** (Device): eight faders per page, banks coloured by Q-Link")
add("  group; press Device again for page 2, once more to exit.")
add("- **Tempo page** (Shift + Device): Up/Down change the BPM.")
add("- **Swing page** (Shift + Stop clip): Up/Down change swing, 50-75%.")
add("- **Step sequencer view** (Sequencer): opens the MPC view; Shift = next bar.")
add()
add("## Colours")
add()
add("| Name | RGB |")
add("|------|-----|")
for _, name in ipairs({ "off", "dim", "available", "white", "green", "red", "orange", "blue", "cyan", "magenta", "yellow" }) do
	local c = P[name]
	if c then
		add(colourRow(name, c))
	end
end
add()
add("## Journal")
add()
add("Every action logs a line through `print`, prefixed `LaunchpadProMK3:`.")
add("Read it with:")
add()
add("```sh")
add("journalctl -u acvs -o cat --no-pager | grep LaunchpadProMK3")
add("```")
add()
add("## Guards")
add()
add("Project-scoped pages refuse to open while no project is loaded or a dialog")
add("owns the UI (`engineMode.CurrentPopup` is not `No Popup`). Each refusal logs")
add("once, for example `quantize: dialog open (New Project)`.")
add()

local fh = assert(io.open(out, "w"))
fh:write(table.concat(lines, "\n"))
fh:close()
io.write("gen-manual: wrote " .. out .. "\n")
